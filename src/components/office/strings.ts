export const OFFICE_STR: Record<'en' | 'ar', OfficeStr> = { en, ar }

export function fmtBytes(n: number, locale: 'en' | 'ar'): string {
  const f = new Intl.NumberFormat(locale === 'ar' ? 'ar-SA' : 'en', { maximumFractionDigits: 1 })
  if (n < 1024) return `${f.format(n)} B`
  if (n < 1024 ** 2) return `${f.format(n / 1024)} KB`
  if (n < 1024 ** 3) return `${f.format(n / 1024 ** 2)} MB`
  return `${f.format(n / 1024 ** 3)} GB`
}
