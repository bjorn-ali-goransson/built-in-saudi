// Regenerate `src/tools/added.ts` — the date each tool first appeared.
//
// Run by hand when tools are added:  node scripts/gen-tool-dates.mjs
//
// The date is DERIVED from git rather than typed into each meta, because a
// hand-written date is a thing 216 files can disagree about and nobody can
// check. `git log --diff-filter=A` names the commit that first added each
// `meta.ts`, which is the same event as the tool shipping.
//
// One traversal, not one per tool: asking git 216 separate questions took about
// six minutes and this takes a second. `--follow` is deliberately NOT used —
// it cannot be combined with multiple paths, and a tool that was renamed
// (`cv-generator` -> `ats-cv-optimizer`) keeps its folder, so the folder's own
// first appearance is still the right answer.
import { execSync } from 'node:child_process'
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'

const log = execSync(
  'git log --diff-filter=A --format=@%as --name-only --reverse -- src/tools',
  { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
)

/** folder -> the earliest date any file in it was added. */
const byDir = new Map()
let date = ''
for (const line of log.split('\n')) {
  if (line.startsWith('@')) { date = line.slice(1); continue }
  const m = /^src\/tools\/([a-z0-9-]+)\//.exec(line.trim())
  if (m && !byDir.has(m[1])) byDir.set(m[1], date)
}

// Map folder -> tool id: the two differ for at least one tool already
// (`zip-inspector` holds `archive-inspector`), and that has cost a debugging
// round before.
const rows = []
const uncommitted = []
// LOCAL midnight, never `toISOString().slice(0, 10)` — east of Greenwich those
// disagree between local midnight and UTC midnight, so on a machine in Riyadh
// (UTC+3) a tool added in the small hours was stamped YESTERDAY. Every date git
// hands back is already local; only this fallback was not, so the one tool with
// no commit behind it sorted below tools added before it. Same bug this repo
// already records for two `id-expiry` test cases, in a script rather than a
// spec.
const today = () => {
  const d = new Date()
  const p = (n) => String(n).padStart(2, '0')
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`
}
for (const dir of readdirSync('src/tools')) {
  const meta = `src/tools/${dir}/meta.ts`
  if (!existsSync(meta)) continue
  const id = /\bid: '([^']+)'/.exec(readFileSync(meta, 'utf8'))?.[1]
  if (!id) continue
  // A folder git has never seen is being added RIGHT NOW, so today is the
  // correct answer rather than an error. Without this the generator refuses on
  // every new tool until a second commit exists, which would make the build
  // guard fire on exactly the case it was written to serve.
  const when = byDir.get(dir) ?? today()
  if (!byDir.has(dir)) uncommitted.push(dir)
  rows.push([id, when])
}

if (uncommitted.length) {
  console.log(`not yet in git, dated today: ${uncommitted.join(', ')}`)
}

rows.sort((a, b) => (a[1] === b[1] ? a[0].localeCompare(b[0]) : b[1].localeCompare(a[1])))
const body = rows.map(([id, when]) => `  '${id}': '${when}',`).join('\n')

writeFileSync('src/tools/added.ts', `// GENERATED by scripts/gen-tool-dates.mjs — do not edit by hand.
//
// The date each tool first appeared, read from git rather than typed, because a
// hand-written date is a thing 216 files can disagree about and nobody can
// check. Regenerate after adding tools; \`check-tool-registry.mjs\` fails the
// build if a live tool is missing from here.
//
// Newest first, which is also the order the catalogue reads it in.
export const ADDED: Record<string, string> = {
${body}
}
`)
console.log(`wrote src/tools/added.ts — ${rows.length} tools, newest ${rows[0][1]}, oldest ${rows[rows.length - 1][1]}`)
