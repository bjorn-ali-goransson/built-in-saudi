// Regenerate `src/tools/popularity.ts` — how often each tool's page was viewed.
//
// Run by hand:  node scripts/gen-popularity.mjs <rollup.json.gz>
//
// The input is the site's own analytics rollup (the console's "history"
// download for this site), saved locally. This script never talks to the
// analytics platform itself: signing in to it needs a credential, and a
// credential has no business in a script that lives in the repo.
//
// What is counted is PAGEVIEWS of `/{en,ar}/apps/<id>` (and the legacy
// `/tools/<id>`, which 301s there), summed over every month in the rollup.
// Sub-paths count for their tool (`/apps/calls/join` is Calls). A path for a
// renamed tool counts for the tool it became, because the visitor wanted the
// same job done; a path for a withdrawn tool counts for nothing.
import { readFileSync, writeFileSync } from 'node:fs'
import { gunzipSync } from 'node:zlib'

const file = process.argv[2]
if (!file) {
  console.error('usage: node scripts/gen-popularity.mjs <rollup.json.gz>')
  process.exit(1)
}

const raw = readFileSync(file)
const rollup = JSON.parse((raw[0] === 0x1f ? gunzipSync(raw) : raw).toString('utf8'))
const paths = rollup.names?.p
if (!Array.isArray(paths) || !Array.isArray(rollup.months) || !Array.isArray(rollup.days)) {
  console.error('gen-popularity: this does not look like an analytics rollup (no names.p / months / days).')
  process.exit(1)
}

// The renames the router redirects, read from the router rather than copied,
// so a future rename cannot leave its old traffic uncounted.
const router = readFileSync('src/router.tsx', 'utf8')
const RENAMED = Object.fromEntries(
  [...router.matchAll(/path: 'apps\/([a-z0-9-]+)', element: <RenamedToolRedirect to="([a-z0-9-]+)"/g)].map((m) => [m[1], m[2]]),
)

const ADDED = Object.fromEntries([...readFileSync('src/tools/added.ts', 'utf8').matchAll(/'([a-z0-9-]+)':\s*'(\d{4}-\d{2}-\d{2})'/g)].map((m) => [m[1], m[2]]))
const live = new Set(Object.keys(ADDED))
if (live.size < 100) {
  console.error(`gen-popularity: found only ${live.size} tools in src/tools/added.ts — the sweep is broken.`)
  process.exit(1)
}

const toolOf = (p) => {
  const m = /^\/(?:en|ar)\/(?:apps|tools)\/([^/?#]+)/.exec(p)
  if (!m) return null
  const id = RENAMED[m[1]] ?? m[1]
  return live.has(id) ? id : null
}

const views = {}
for (const month of rollup.months) {
  for (const [i, n] of month.p ?? []) {
    const id = toolOf(paths[i])
    if (id) views[id] = (views[id] ?? 0) + n
  }
}
const days = rollup.days.map((d) => d.d).filter(Boolean).sort()
const from = days[0]
const to = days[days.length - 1]

// A tool added after the last day measured gets NO row rather than a zero: it
// was never on the site while the counting happened, and "nobody opened it" is
// a different statement from "nobody could have".
const rows = [...live].filter((id) => ADDED[id] <= to).sort().map((id) => `  '${id}': ${views[id] ?? 0},`).join('\n')
writeFileSync('src/tools/popularity.ts', `// GENERATED by scripts/gen-popularity.mjs from the site's analytics rollup.
// Do not edit by hand: re-run the script on a fresh rollup instead.
//
// Pageviews of each tool's page over the window below. A tool with no row was
// added after the rollup was taken and has never been measured.

/** The days the counts cover, inclusive, in the site's own time zone. */
export const MEASURED = { from: '${from}', to: '${to}' } as const

export const VIEWS: Record<string, number> = {
${rows}
}
`)
const counted = Object.values(views).reduce((a, b) => a + b, 0)
console.log(`wrote src/tools/popularity.ts: ${live.size} tools, ${counted} views, ${from} to ${to}`)
